import { resolve } from "path";

import preact from "@preact/preset-vite";
import tailwindcss from "@tailwindcss/vite";
import react from "@vitejs/plugin-react";
import browserslistToEsbuild from "browserslist-to-esbuild";
import type { AtRule, Plugin as PostcssPlugin } from "postcss";
import { defineConfig, type Plugin } from "vite";

import { CSS_TARGET } from "./css-target";

// The build of core-ui is only for its CSS (the wrappers bundle its sources):
// drops everything else from the output
const cssOnly = (): Plugin => ({
  name: "css-only",
  generateBundle(_, bundle) {
    for (const [fileName, output] of Object.entries(bundle)) {
      if (!output.fileName.endsWith(".css")) {
        delete bundle[fileName];
      }
    }
  },
});

/** Replaces an at-rule by its content */
const unwrap = (rule: AtRule) => {
  rule.replaceWith(rule.nodes ?? []);
};

/**
 * Makes the CSS generated by Tailwind work in the shadow root of the web
 * component, and keeps the browsers it supported working (Tailwind 4 needs
 * Safari 16.4, Chrome 111 and Firefox 128)
 */
const tailwindCompat = (): PostcssPlugin => ({
  postcssPlugin: "tailwind-compat",
  OnceExit(root) {
    // The initial values of Tailwind's variables (for shadows, transforms,
    // gradients...) are registered with @property, which a shadow root
    // ignores: sets them on all elements instead, as Tailwind does for the
    // browsers lacking @property
    root.walkAtRules("layer", layer => {
      if (layer.params === "properties") {
        layer.walkAtRules("supports", unwrap);
      }
    });

    // Colors with an opacity (bg-foreground/60) are mixed with transparent,
    // falling back to the opaque color without color-mix(): the hsl() of
    // the theme colors takes the opacity in all browsers
    root.walkDecls(decl => {
      decl.value = decl.value.replace(
        /color-mix\(in oklab,\s*hsl\((var\(--[\w-]+\))\)\s+([\d.]+%),\s*transparent\)/g,
        "hsl($1 / $2)"
      );
    });
    root.walkAtRules("supports", supports => {
      if (!supports.params.includes("color-mix")) {
        return;
      }

      // The rules which no longer need color-mix() apply to all browsers,
      // after their opaque fallback. Others, colors the regex doesn't
      // know, fail the build (except the placeholders' one, of Tailwind's
      // base styles)
      supports.each(rule => {
        const css = rule.toString();
        if (!css.includes("color-mix(")) {
          supports.before(rule);
        } else if (!css.includes("currentcolor")) {
          throw rule.error("Opaque without color-mix(), see tailwindCompat");
        }
      });

      if (!supports.nodes?.length) {
        supports.remove();
      }
    });
  },
});

export default defineConfig(({ command, mode }) => {
  const isPreactDev = mode === "development-preact";

  return {
    // The framework plugin is only for the dev app (index.html)
    plugins: [
      tailwindcss(),
      command === "serve" ? (isPreactDev ? preact() : react()) : cssOnly(),
    ],

    css: {
      postcss: { plugins: [tailwindCompat()] },
    },
    define: {
      "process.env": {
        NODE_ENV: mode,
      },
    },
    build: {
      outDir: "dist",
      rolldownOptions: {
        input: resolve(import.meta.dirname, "src/index.css"),
        output: {
          assetFileNames: "style.[ext]",
        },
      },
      target: browserslistToEsbuild(),
      cssTarget: CSS_TARGET,
      copyPublicDir: false,
    },

    resolve: {
      alias: isPreactDev
        ? {
            react: "preact/compat",
            "react-dom": "preact/compat",
          }
        : undefined,
    },
  };
});
